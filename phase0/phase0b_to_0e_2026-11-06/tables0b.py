"""Tables for RESULTS_PHASE0B.md (Phase 0b to 0e), generated from the JSON outputs; prints Markdown.

  python -I tables0b.py > TABLES_PHASE0B.md
"""
import os, json, pickle
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def j(path):
    p = os.path.join(HERE, path)
    return json.load(open(p)) if os.path.exists(p) else None


def pct(x, nd=2):
    if x is None:
        return "-"
    x = 0.0 if abs(x) < 0.5 * 10 ** (-nd - 2) else x                  # no "-0.00%"
    return ("%." + str(nd) + "f%%") % (100 * x)


def num(x, nd=3):
    return "-" if x is None else ("%." + str(nd) + "f") % x


out = ["# Phase 0b to 0e: tables", "",
       "Generated by tables0b.py from out0b/, out0c/, out0d/ and out0e/. Frequencies: e_i = omega~_i / omega_i - 1. "
       "H4 measure: median over the held-out geometries of the median of e_1..e_5; H5 measure: median reproduced notch drop; "
       "H6 measure: median over the geometries of E2 (median over each geometry's 10 evaluation cases). "
       "'max e': the largest e_i of a geometry (median and maximum over geometries).", ""]

# ----------------------------------------------------------------------------- Phase 0b
b = j("out0b/evalfam2.json")
if b:
    out += ["## 1. Pilot 2 (24 training, 16 held-out geometries; 13 of 16 inside the training hull), Phase 0b", "",
            "| Basis | H4 measure | H5 measure | H5, drops >= 1% (n) | H6 measure | median e_1 | max e: median | max e: maximum | slope, R^2 of omega_1 |",
            "|---|---|---|---|---|---|---|---|---|"]
    names = dict(modal_m8="modal truncation", net_o4="O4, shared network, 60,000 it.", net_o3s="O3s, shared network, 60,000 it.",
                 rb_k1="unmapped reduced basis, k = 1", rb_k4="unmapped reduced basis, k = 4", rb_all="unmapped reduced basis, all 24")
    for k in ("modal_m8", "net_o4", "net_o3s", "rb_k1", "rb_k4", "rb_all"):
        s = b["summary_held"][k]
        out.append("| %s | %s | %s | %s (%d) | %s | %s | %s | %s | %s, %s |" % (
            names[k], pct(s["H4"]), pct(s["H5"], 1), pct(s["H5_drop_ge_1pct"], 1), s["n_big"], pct(s["H6"], 1),
            pct(s["median_e1"]), pct(s["median_max_ritz"]), pct(s["max_max_ritz"]), num(s["slope"]), num(s["r2"])))
    r = b["threshold_rule"]
    out += ["", "Threshold rule (PHASE0B_PLAN.md): H4 <= %s, H5 >= %s, H6 <= %s; kept as planned: %s; H7 direction seen: %s." % (
        pct(r["H4"], 0), pct(r["H5"], 0), pct(r["H6"], 0), r["kept_from_plan"], r["H7_direction_seen"]), ""]
    t = b["summary_train"]
    out += ["Training geometries (24): O4 max e median %s, maximum %s, median drop %s; O3s max e median %s, maximum %s, median drop %s." % (
        pct(t["net_o4"]["median_max_ritz"]), pct(t["net_o4"]["max_max_ritz"]), pct(t["net_o4"]["median_drop"], 1),
        pct(t["net_o3s"]["median_max_ritz"]), pct(t["net_o3s"]["max_max_ritz"]), pct(t["net_o3s"]["median_drop"], 0)), ""]
    out += ["### Per held-out geometry, O4 (shared network, 60,000 iterations)", "",
            "| x_c, d | inside hull | distance | FE drop | median e_1..e_5 | max e | drop reproduced | E2 | E1 tip acc. |", "|---|---|---|---|---|---|---|---|---|"]
    rows = sorted(b["held"].items(), key=lambda kv: kv[1]["net_o4"]["e2_energy"]["median"])
    for G, g in rows:
        n = g["net_o4"]
        out.append("| %s | %s | %.3f | %s | %s | %s | %.3f | %s | %s |" % (
            G.replace("_", ", "), "yes" if g["inside_hull"] else "no", g["dist_nearest"], pct(g["w1_drop_fe"]),
            pct(float(np.median(n["ritz"][:5])), 3), pct(max(n["ritz"])), n["drop_reproduced"], pct(n["e2_energy"]["median"], 1),
            pct(n["e1_tip_acc"]["median"], 1)))
    out.append("")

# ----------------------------------------------------------------------------- Phase 0d
dd = j("out0d/eval0d.json")
if dd and b:
    out += ["## 2. Classical controls on pilot 2, Phase 0d", "",
            "| Control | H4 measure | H5 measure | H6 measure | median e_1 | max e: median | max e: maximum | slope, R^2 of omega_1 | rank, median |",
            "|---|---|---|---|---|---|---|---|---|"]
    names = dict(rbm_k4="mapped reduced basis, k = 4", rbm_all="mapped reduced basis, all 24 (truncation 1e-10, planned)",
                 rbm_all_t13="mapped reduced basis, all 24 (truncation 1e-13, deviation 4)",
                 freq_rbf="frequency regression (thin-plate spline)", freq_nearest="frequencies of the nearest training geometry")
    for k in ("rbm_k4", "rbm_all", "rbm_all_t13", "freq_rbf", "freq_nearest"):
        s = dd["summary_pilot2"][k]
        h4 = s.get("H4_abs", s["H4"])
        e1 = s.get("median_abs_e1", s["median_e1"])
        out.append("| %s | %s%s | %s | %s | %s%s | %s | %s | %s, %s | %s |" % (
            names[k], pct(h4, 3), " (abs.)" if "H4_abs" in s else "", pct(s["H5"], 1), pct(s.get("H6"), 1),
            pct(e1, 3), " (abs.)" if "median_abs_e1" in s else "", pct(s["median_max_ritz"]), pct(s["max_max_ritz"]),
            num(s["slope"]), num(s["r2"]), "%d" % s["median_rank"] if "median_rank" in s else "-"))
    out += ["", "rbm_k4 with truncation 1e-13 is identical to rbm_k4 (rank 32 of 32 in both). Nodes of the held-out geometry that "
            "land in the notch void of a source (check B3): median over geometries of the mean over sources %s, largest %s." % (
                pct(dd["summary_pilot2"]["rbm_all"]["median_void_mean"]), pct(dd["summary_pilot2"]["rbm_all"]["max_void_max"])), ""]
    out += ["### Per held-out geometry: O4 network against the mapped reduced basis (all 24, truncation 1e-13) and the frequency regression", "",
            "| x_c, d | inside hull | O4: max e | O4: drop | O4: E2 | RB: max e | RB: drop | RB: E2 | regression: max abs. e | regression: drop |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    rows = sorted(dd["pilot2"].items(), key=lambda kv: -max(kv[1]["rbm_all_t13"]["ritz"]))
    for G, g in rows:
        n, r, f = b["held"][G]["net_o4"], g["rbm_all_t13"], g["freq_rbf"]
        out.append("| %s | %s | %s | %.3f | %s | %s | %.3f | %s | %s | %.3f |" % (
            G.replace("_", ", "), "yes" if b["held"][G]["inside_hull"] else "no", pct(max(n["ritz"])), n["drop_reproduced"],
            pct(n["e2_energy"]["median"], 1), pct(max(r["ritz"])), r["drop_reproduced"], pct(r["e2_energy"]["median"], 1),
            pct(max(np.abs(f["ritz"]))), f["drop_reproduced"]))
    nb = sum(1 for G, g in dd["pilot2"].items() if max(g["rbm_all_t13"]["ritz"]) < max(b["held"][G]["net_o4"]["ritz"]))
    ne = sum(1 for G, g in dd["pilot2"].items() if g["rbm_all_t13"]["e2_energy"]["median"] < b["held"][G]["net_o4"]["e2_energy"]["median"])
    out += ["", "The mapped reduced basis has the smaller largest error on %d of 16 geometries and the smaller E2 on %d of 16." % (nb, ne), ""]
    out += ["### Phase 0 pilot (8 training geometries, 4 held out, 3 of them outside the training hull)", "",
            "| Basis | H4 measure | H5 measure | H6 measure | max e: maximum |", "|---|---|---|---|---|"]
    rb1 = j("out0b/rb1.json")
    if rb1:
        G = list(rb1["geoms"].values())
        for k, nm in (("net_o4", "O4 network of Phase 0 (shared, 60,000 it.)"), ("rb_all", "unmapped reduced basis, all 8")):
            out.append("| %s | %s | %s | %s | %s |" % (nm, pct(float(np.median([np.median(g[k]["ritz"][:5]) for g in G]))),
                                                       pct(float(np.median([g[k]["drop_reproduced"] for g in G])), 1),
                                                       pct(float(np.median([g[k]["e2_energy"]["median"] for g in G])), 1),
                                                       pct(max(max(g[k]["ritz"]) for g in G))))
    for k, nm in (("rbm_all_t13", "mapped reduced basis, all 8 (truncation 1e-13)"), ("freq_rbf", "frequency regression")):
        s = dd["summary_pilot1"][k]
        out.append("| %s | %s | %s | %s | %s |" % (nm, pct(s.get("H4_abs", s["H4"])), pct(s["H5"], 1), pct(s.get("H6"), 1), pct(s["max_max_ritz"])))
    out.append("")

# ----------------------------------------------------------------------------- Phase 0c
c = j("out0c/eval0c.json")
out += ["## 3. One network per mode on G0, Phase 0c (20,000 iterations)", ""]
logs = {}
for fn in sorted(os.listdir(os.path.join(HERE, "logs0c"))):
    if fn.startswith("sep_") and fn.endswith(".log"):
        L = [json.loads(l) for l in open(os.path.join(HERE, "logs0c", fn)) if l.startswith("{")]
        if L and L[-1]["t"] == 20000:
            logs[fn[:-4]] = L[-1]["ritz"]
shared = {}
for o in ("o2", "o3", "o4"):
    for s in (0, 1, 2):
        fn = os.path.join(HERE, "logs", "train_%s_s%d.log" % (o, s))
        if os.path.exists(fn):
            L = [json.loads(l) for l in open(fn) if l.startswith("{")]
            if L and L[-1]["t"] == 20000:
                shared["%s_s%d" % (o, s)] = L[-1]["ritz"]
out += ["| Run | e_1 | e_2 | e_3..e_8, max | max e | source |", "|---|---|---|---|---|---|"]
for k, r in sorted(logs.items()):
    src = "eval0c.json" if c and k in c else "training log, t = 20,000"
    rr = c[k]["ritz"] if c and k in c else r
    out.append("| per mode, %s | %s | %s | %s | %s | %s |" % (k[4:].replace("_s", ", seed "), pct(rr[0]), pct(rr[1]), pct(max(rr[2:])), pct(max(rr)), src))
for k, r in sorted(shared.items()):
    out.append("| shared (Phase 0), %s | %s | %s | %s | %s | training log, t = 20,000 |" % (k.replace("_s", ", seed "), pct(r[0]), pct(r[1]), pct(max(r[2:])), pct(max(r))))
out.append("")

# ----------------------------------------------------------------------------- Phase 0e
e = j("out0e/evalfam0e.json")
if e:
    out += ["## 4. Architecture on pilot 2 at 30,000 iterations, Phase 0e", "",
            "| Run | H4 measure | H5 measure | H6 measure | median e_1 | max e: median | max e: maximum | slope, R^2 | training: max e median, maximum |",
            "|---|---|---|---|---|---|---|---|---|"]
    for k, s in e["summary_held"].items():
        t = e["summary_train"].get(k)
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s, %s | %s |" % (
            k, pct(s["H4"]), pct(s["H5"], 1), pct(s["H6"], 1), pct(s["median_e1"]), pct(s["median_max_ritz"]), pct(s["max_max_ritz"]),
            num(s["slope"]), num(s["r2"]), "-" if t is None else "%s, %s" % (pct(t["median_max_ritz"]), pct(t["max_max_ritz"]))))
    tt = {}
    for fn in sorted(os.listdir(os.path.join(HERE, "out0e"))):
        if fn.startswith("fam2") and fn.endswith(".pkl"):
            d = pickle.load(open(os.path.join(HERE, "out0e", fn), "rb"))
            tt["%s_%s_%d" % (d["arch"], d["obj"], d["iters"])] = d["t_train"]
    out += ["", "Training time (s): " + ", ".join("%s %.0f" % kv for kv in sorted(tt.items())) + ".", ""]

print("\n".join(out))
