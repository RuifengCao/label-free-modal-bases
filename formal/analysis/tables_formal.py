"""Tables of the formal runs of the Unified 2027 dynamics paper (pre-registration Version 1, stamped 7 November 2026).

Reads the outputs copied from the laptop (results/, byte-identical to the laptop's files: SHA256SUMS_formal_results.txt)
and writes TABLES_FORMAL.md and summary_formal.json. Every number is read from the outputs or computed from them here;
nothing is typed in by hand.

Usage: python3 tables_formal.py results
"""
import glob
import json
import os
