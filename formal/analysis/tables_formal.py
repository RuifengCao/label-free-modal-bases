def summ(m, ks):
    E = np.abs(np.array([G[k][m]["ritz"] for k in ks]))
    r = dict(h4=float(np.median(np.median(E[:, :5], axis=1))), h5=float(np.median([G[k][m]["drop_reproduced"] for k in ks])),
             e1_med=float(np.median(np.array([G[k][m]["ritz"][0] for k in ks]))), maxe_med=float(np.median(E.max(1))), maxe_max=float(E.max()))
    if "e2_energy" in G[ks[0]][m]:
        r.update(h6=float(np.median([G[k][m]["e2_energy"]["median"] for k in ks])),
                 e1d=float(np.median([G[k][m]["e1_tip_disp"]["median"] for k in ks])),
                 e1a=float(np.median([G[k][m]["e1_tip_acc"]["median"] for k in ks])))
    return r


