NAME = {"o1": "O1", "o2": "O2", "o3": "O3", "o4": "O4", "o3s": "O3s", "sup": "supervised"}
out, S = [], {}


def pct(v):
    """A fraction as a percentage with three significant figures (0 for round-off below 1e-6 %)."""
    v = 100.0 * float(v)
    if abs(v) < 1e-6:
        return "0"
    return "%.3g" % v


def w(line=""):
    out.append(line)


def table(header, rows):
    w("| " + " | ".join(header) + " |")
    w("|" + "---|" * len(header))
    for r in rows:
        w("| " + " | ".join(str(x) for x in r) + " |")
    w()


def load_json(name):
    with open(os.path.join(R, name)) as f:
        return json.load(f)


# ----------------------------------------------------------------------------------------------- run record
prog = open(os.path.join(R, "progress.txt")).read().splitlines()
env = load_json("environment.json")
state = load_json("state.json")
V = load_json("verdicts.json")
dur = {m.group(1): int(m.group(2)) for m in (re.search(r"  (\S+): done in (\d+) s", l) for l in prog) if m}
import datetime as _dt


def dmy(stamp):
    t = _dt.datetime.strptime(stamp, "%Y-%m-%d %H:%M:%S")
    return "%d %s %d, %s" % (t.day, t.strftime("%B"), t.year, t.strftime("%H:%M:%S"))


